/** The shared id for an exercise id that may be an old web-only built-in id. */
export function canonicalExerciseId(id: string): string {
  return LEGACY_CORE_EXERCISE_IDS[id] ?? id;
}

/** A LogIt exercise by id (old web ids accepted). */
export function coreExerciseById(id: string): Exercise | undefined {
  return BY_ID.get(canonicalExerciseId(id));
}

/** A core or custom exercise by name, case-insensitive. */
export function findExerciseByName<T extends { name: string }>(list: T[], name: string): T | undefined {
  const q = name.trim().toLowerCase();
  return list.find((e) => e.name.toLowerCase() === q);
}
