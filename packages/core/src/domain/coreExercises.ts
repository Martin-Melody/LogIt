import type { Equipment, Exercise, ExerciseType, MuscleGroup } from "./exercise";

/**
 * LogIt's strength bank: the exercises every account has. The phone seeds them into its
 * database (new ones are added on update, never overwriting what's there); the web
 * dashboard reads this list directly.
 *
 * Ids are permanent. They are `core_<name as snake case>` because that's what the phone has
 * always given its bundled exercises (see sqlite.ts coreExerciseId), and synced history
 * already carries them. Never derive an id from a name at runtime: renaming an entry here
 * must keep its id.
 */

type Muscles = MuscleGroup[];

function ex(
  id: string,
  name: string,
  primary: Muscles,
  secondary: Muscles,
  equipment: Equipment,
  cues: string[],
  extra: { exerciseType?: ExerciseType; notes?: string } = {},
): Exercise {
  return {
    id,
    name,
    notes: extra.notes ?? null,
    isCore: true,
    createdAtMs: 0,
    primaryMuscles: primary,
    secondaryMuscles: secondary,
    equipment,
    cues,
    ...(extra.exerciseType ? { exerciseType: extra.exerciseType } : {}),
  };
}

